def load(tag):
    S = pd.read_csv(R / tag / "station_sums.csv", dtype={"case": str}); P = pd.read_csv(R / tag / "precip_sums.csv", dtype={"case": str})
    return S[(S.interp == "bilinear") & (S.region == "CONUS")], P
def st(d):
    g = d[["n", "sd", "ssq"]].sum(); return np.sqrt(g.ssq / g.n), g.sd / g.n, int(g.n)
(So, Po), (Sn, Pn) = load("phase1-obs"), load("phase1b-obs")
def pool(S, m, v, lo=12, hi=84, case=None):
    d = S[(S.model == m) & (S["var"] == v) & (S.lead >= lo) & (S.lead <= hi)]
    if case: d = d[d.case == case]
    return st(d)
