def parse_frozen(f):
    rows = {}
    for l in Path(f).read_text().splitlines():
        m = re.match(r"(\d{10})\s+(\S+)\s+f(\d+) cold pts\s+(\d+) frozen frac 0-10 ([\d.]+) 10-40 ([\d.]+)", l)
        if m: rows[(m[1], m[2], int(m[3]))] = (float(m[5]), float(m[6]))
        else:
            m = re.match(r"(\d{10})\s+(\S+)\s+(\S+)\s+(\d+)\s+([\d.]+)\s+([\d.]+)", l)
            if m: rows[(m[1], m[2], int(m[3][1:]))] = (float(m[5]), float(m[6]))
    return rows
